import JSZip from 'jszip';
import { DesignProject, GeneratedWebsiteBundle } from '../types/design';
import { compileProjectToCode } from './designEngine';

function getExtensionFromMime(mime: string): string {
  if (mime.includes('png')) return 'png';
  if (mime.includes('webp')) return 'webp';
  if (mime.includes('svg')) return 'svg';
  if (mime.includes('gif')) return 'gif';
  return 'jpg';
}

export async function exportProjectAsZip(
  project: DesignProject,
  bundle?: GeneratedWebsiteBundle
): Promise<{ filename: string; fileCount: number; byteSize: number }> {
  const compiled = bundle || project.lastGeneratedBundle || compileProjectToCode(project);
  const zip = new JSZip();
  const assetsFolder = zip.folder('assets');

  const slug =
    project.name
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-|-$/g, '') || 'sitecraft-website';

  let htmlOut = compiled.html;
  let reactOut = compiled.react;
  let assetCounter = 1;

  // Collect all image elements across all pages and bundle their images into /assets/ inside the ZIP
  const processedSrcMap = new Map<string, string>();

  for (const page of project.pages) {
    for (const el of Object.values(page.elements)) {
      if (el.type === 'image' && el.assets.src) {
        const src = el.assets.src;
        if (processedSrcMap.has(src)) continue;

        if (src.startsWith('data:image/')) {
          // Extract base64 data URL into a real binary file inside /assets/
          const match = src.match(/^data:(image\/[a-zA-Z0-9+.-]+);base64,(.+)$/);
          if (match && assetsFolder) {
            const mime = match[1];
            const base64Data = match[2];
            const ext = getExtensionFromMime(mime);
            const cleanName = (el.name || `image_${assetCounter}`)
              .toLowerCase()
              .replace(/[^a-z0-9_-]+/g, '_');
            const assetFilename = `${cleanName}_${assetCounter}.${ext}`;
            assetCounter++;

            assetsFolder.file(assetFilename, base64Data, { base64: true });
            const relativePath = `assets/${assetFilename}`;
            processedSrcMap.set(src, relativePath);
          }
        } else if (src.startsWith('/src/assets/')) {
          // Fetch built-in studio image so the exported ZIP has real local image files
          try {
            const response = await fetch(src);
            if (response.ok && assetsFolder) {
              const arrayBuffer = await response.arrayBuffer();
              const parts = src.split('/');
              const rawFilename = parts[parts.length - 1] || `studio_${assetCounter}.jpg`;
              assetsFolder.file(rawFilename, arrayBuffer);
              const relativePath = `assets/${rawFilename}`;
              processedSrcMap.set(src, relativePath);
              assetCounter++;
            }
          } catch {
            // Keep original path if fetch fails
          }
        }
      }
    }
  }

  // Rewrite all bundled image paths in HTML and React code to point to `assets/<filename>`
  for (const [originalSrc, relativeZipPath] of processedSrcMap.entries()) {
    htmlOut = htmlOut.split(originalSrc).join(relativeZipPath);
    reactOut = reactOut.split(originalSrc).join(relativeZipPath);
  }

  // 1. Standalone HTML entry point
  zip.file('index.html', htmlOut);

  // 2. Extracted CSS stylesheet
  zip.file('styles.css', compiled.css);

  // 3. Interactive JavaScript runtime
  zip.file('script.js', compiled.js);

  // 4. React component export
  const srcFolder = zip.folder('react-src');
  if (srcFolder) {
    srcFolder.file('App.tsx', reactOut);
    srcFolder.file('styles.css', compiled.css);
  }

  // 5. Structured SITECRAFT JSON Design Document
  zip.file('sitecraft-design.json', JSON.stringify(project, null, 2));

  // 6. Comprehensive README with launch instructions
  const readmeContent = `# ${project.name}
Generated by **SITECRAFT** — *Design once. Build instantly.*

- **Template Base**: ${project.templateId}
- **Category**: ${project.category}
- **Pages**: ${project.pages.map((p) => p.name).join(', ')}
- **Bundled Image Assets**: ${processedSrcMap.size} file(s) in \`/assets/\`
- **Compiler Engine**: ${compiled.providerMessage}
- **Exported At**: ${new Date().toLocaleString()}

---

## Quick Start (HTML / CSS / JS)

1. Unzip this archive into a folder.
2. Open \`index.html\` directly in any modern browser (Chrome, Edge, Firefox, Safari), or serve it locally:

\`\`\`bash
npx serve .
\`\`\`

## Project Files Included

- \`index.html\` — Complete semantic HTML5 document with responsive layout and local \`assets/\` image paths.
- \`styles.css\` — Extracted stylesheet with Desktop, Tablet (\`@media (max-width: 1024px)\`), and Mobile (\`@media (max-width: 640px)\`) breakpoints.
- \`script.js\` — Client-side navigation and button micro-interaction script.
- \`assets/\` — All custom uploaded images and studio photography used in your project.
- \`react-src/App.tsx\` — Ready-to-mount React component version of your design.
- \`sitecraft-design.json\` — Full SITECRAFT structured JSON design document.
`;

  zip.file('README.md', readmeContent);

  const blob = await zip.generateAsync({ type: 'blob' });
  const filename = `${slug}-sitecraft-export.zip`;

  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = filename;
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);
  setTimeout(() => URL.revokeObjectURL(url), 2500);

  return {
    filename,
    fileCount: 6 + processedSrcMap.size,
    byteSize: blob.size,
  };
}
